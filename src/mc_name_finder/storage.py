"""Timestamped scan reports and atomically replaced checkpoints."""

import csv
import io
import json
from datetime import datetime, timezone
from pathlib import Path

from . import __version__
from .words import Candidate

ATTRIBUTION = (
    "Word candidates use wordfreq by Robyn Speer (Apache-2.0 code; CC BY-SA 4.0 data). "
    "https://github.com/rspeer/wordfreq — SUBTLEX data by Marc Brysbaert and collaborators "
    "is freely available. See upstream README for all corpus credits. "
    "Reports transform candidates into normalized Minecraft names and add API observations. "
    "Derived word data remains subject to CC BY-SA 4.0: "
    "https://creativecommons.org/licenses/by-sa/4.0/. "
    "Custom word lists retain their respective licenses."
)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def atomic_write(path: Path, text: str) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def checkpoint(output: Path, candidates: list[Candidate], metadata: dict) -> None:
    output.mkdir(parents=True, exist_ok=True)
    atomic_write(
        output / "results.json",
        json.dumps(
            {
                "schema_version": 1,
                "tool_version": __version__,
                "exported_at_utc": utc_now(),
                "attribution": ATTRIBUTION,
                "metadata": metadata,
                "candidates": [c.to_dict() for c in candidates],
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
    )


def load_report(output: Path) -> tuple[list[Candidate], dict]:
    data = json.loads((output / "results.json").read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema_version") != 1:
        raise ValueError("Unsupported report schema; use a report generated by this tool.")
    rows = data.get("candidates")
    if not isinstance(rows, list) or not isinstance(data.get("metadata"), dict):
        raise ValueError("Invalid report format.")
    candidates = [Candidate(**row) for row in rows]
    # A report is user-editable: validate names before interpolating them into API URLs.
    if any(
        not c.name.isascii()
        or not c.name.isalpha()
        or not 2 <= len(c.name) <= 16
        or c.name != c.name.lower()
        for c in candidates
    ):
        raise ValueError("Report contains invalid candidate names.")
    if len({c.name for c in candidates}) != len(candidates):
        raise ValueError("Report contains duplicate candidate names.")
    return candidates, data["metadata"]


def export_report(output: Path, candidates: list[Candidate], metadata: dict) -> None:
    checkpoint(output, candidates, metadata)
    rows = sorted(candidates, key=lambda c: (len(c.name), -c.score, c.name))
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer)
    writer.writerow(
        [
            "name",
            "length",
            "languages",
            "original_words",
            "lookup_status",
            "exact_status",
            "lookup_checked_at_utc",
            "exact_checked_at_utc",
        ]
    )
    for c in rows:
        writer.writerow(
            [
                c.name,
                len(c.name),
                "/".join(c.languages),
                "/".join(c.originals),
                c.lookup_status,
                c.exact_status,
                c.lookup_checked_at_utc,
                c.exact_checked_at_utc,
            ]
        )
    atomic_write(output / "results.csv", "\ufeff" + buffer.getvalue())
    lengths = sorted({len(c.name) for c in candidates})
    # Remove stale lists if --overwrite changes the length range.
    for old in output.glob("*_letters.txt"):
        if old.name.startswith(("unregistered_", "available_exact_")):
            old.unlink()
    for length in lengths:
        for prefix, predicate in (
            ("unregistered", lambda c: c.lookup_status == "UNREGISTERED"),
            ("available_exact", lambda c: c.exact_status == "AVAILABLE"),
        ):
            names = [c.name for c in rows if len(c.name) == length and predicate(c)]
            atomic_write(
                output / f"{prefix}_{length}_letters.txt",
                "".join(f"{name}\n" for name in names),
            )
    atomic_write(
        output / "NOTICE.txt",
        ATTRIBUTION + "\n\n"
        "UNREGISTERED is not confirmed availability. Each observation has its own UTC "
        "timestamp in results.csv/results.json. Text lists must accompany these reports "
        "and this notice when shared. Export time is not check time.\n",
    )
